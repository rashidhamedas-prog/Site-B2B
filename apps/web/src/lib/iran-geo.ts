export function isIranProvince(value: string): value is IranProvince {
  return (IRAN_PROVINCES as readonly string[]).includes(value);
}

export function citiesForProvince(province: string): readonly string[] {
  if (!isIranProvince(province)) return [];
  return IRAN_CITIES[province];
}

export function defaultCityForProvince(province: string): string {
  return citiesForProvince(province)[0] || '';
}

export function citySelectValue(province: string, city: string): string {
  const list = citiesForProvince(province);
  if (city && list.includes(city)) return city;
  if (city) return OTHER_CITY;
  return list[0] || OTHER_CITY;
}
