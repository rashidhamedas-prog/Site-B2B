export function matchCategorySeed(name: string): CategorySeoSeed | null {
  const n = String(name || '').trim();
  if (!n) return null;
  for (const seed of CATEGORY_SEO_SEEDS) {
    if (seed.match.test(n)) return seed;
  }
  return null;
}

export function matchCategorySeedBySlug(slug: string): CategorySeoSeed | null {
  const key = String(slug || '').trim();
  if (!key) return null;
  return CATEGORY_SEO_SEEDS.find((seed) => seed.slug === key) || null;
}

